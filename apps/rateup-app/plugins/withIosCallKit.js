const fs = require("fs");
const path = require("path");
const {
  IOSConfig,
  withAppDelegate,
  withDangerousMod,
  withInfoPlist,
  withXcodeProject,
} = require("expo/config-plugins");

/**
 * WhatsApp calls on iOS: CallKit's incoming-call screen, woken by PushKit VoIP pushes so a
 * call rings even while the app is closed and the phone is locked.
 *
 * iOS 13+ kills an app that receives a VoIP push without reporting a call to CallKit before
 * the push handler returns — JavaScript is far too late for that. So the handler is native:
 * `RateUpVoip` (Objective-C, written below) reports the call through react-native-callkeep
 * and hands the payload to react-native-voip-push-notification, and the AppDelegate forwards
 * PushKit's delegate calls to it.
 *
 * Android does none of this: calls ring there through modules/rateup-calls.
 */

const HELPER = "RateUpVoip";

const HEADER = `// Generated by plugins/withIosCallKit.js — edit the plugin, not this file.
#import <Foundation/Foundation.h>
#import <PushKit/PushKit.h>

NS_ASSUME_NONNULL_BEGIN

@interface ${HELPER} : NSObject

/** CallKit's provider and the PushKit registry; must run at launch, before any VoIP push. */
+ (void)setup NS_SWIFT_NAME(setup());

+ (void)didUpdateCredentials:(PKPushCredentials *)credentials
                        type:(NSString *)type NS_SWIFT_NAME(didUpdate(credentials:type:));

+ (void)didReceiveIncomingPush:(PKPushPayload *)payload
                          type:(NSString *)type
                    completion:(void (^)(void))completion
    NS_SWIFT_NAME(didReceiveIncomingPush(payload:type:completion:));

@end

NS_ASSUME_NONNULL_END
`;

const SOURCE = `// Generated by plugins/withIosCallKit.js — edit the plugin, not this file.
#import "${HELPER}.h"
#import <RNCallKeep/RNCallKeep.h>
#import <RNVoipPushNotification/RNVoipPushNotificationManager.h>

@implementation ${HELPER}

+ (void)setup
{
  [RNCallKeep setup:@{
    @"appName" : @"RateUp",
    @"supportsVideo" : @NO,
    @"maximumCallGroups" : @"1",
    @"maximumCallsPerCallGroup" : @"1",
    @"includesCallsInRecents" : @NO,
  }];
  [RNVoipPushNotificationManager voipRegistration];
}

+ (void)didUpdateCredentials:(PKPushCredentials *)credentials type:(NSString *)type
{
  [RNVoipPushNotificationManager didUpdatePushCredentials:credentials forType:type];
}

+ (void)didReceiveIncomingPush:(PKPushPayload *)payload
                          type:(NSString *)type
                    completion:(void (^)(void))completion
{
  NSDictionary *data = payload.dictionaryPayload;
  // The API sends the call's own id as \`uuid\`; JavaScript maps CallKit's events back by it.
  NSString *uuid = [data[@"uuid"] isKindOfClass:NSString.class] ? data[@"uuid"] : [[NSUUID UUID] UUIDString];
  NSString *handle = [data[@"handle"] isKindOfClass:NSString.class] ? data[@"handle"] : @"";
  NSString *caller = [data[@"callerName"] isKindOfClass:NSString.class] ? data[@"callerName"] : handle;

  // Queued for JavaScript, which may not be running yet.
  [RNVoipPushNotificationManager didReceiveIncomingPushWithPayload:payload forType:type];
  // Reported before returning, as iOS requires; PushKit's completion runs once CallKit has it.
  [RNCallKeep reportNewIncomingCall:uuid
                             handle:handle
                         handleType:@"number"
                           hasVideo:NO
                localizedCallerName:caller
                    supportsHolding:NO
                       supportsDTMF:NO
                   supportsGrouping:NO
                 supportsUngrouping:NO
                        fromPushKit:YES
                            payload:data
              withCompletionHandler:completion];
}

@end
`;

const DELEGATE_METHODS = `
  // PushKit (plugins/withIosCallKit.js): VoIP pushes ring calls through CallKit, even while
  // the app is closed.
  public func pushRegistry(
    _ registry: PKPushRegistry,
    didUpdate pushCredentials: PKPushCredentials,
    for type: PKPushType
  ) {
    ${HELPER}.didUpdate(credentials: pushCredentials, type: type.rawValue)
  }

  public func pushRegistry(
    _ registry: PKPushRegistry,
    didReceiveIncomingPushWith payload: PKPushPayload,
    for type: PKPushType,
    completion: @escaping () -> Void
  ) {
    ${HELPER}.didReceiveIncomingPush(payload: payload, type: type.rawValue, completion: completion)
  }

`;

function replaceOnce(contents, find, replace, what) {
  if (contents.includes(replace)) return contents;
  if (!contents.includes(find)) {
    throw new Error(
      `[withIosCallKit] Could not find ${what} in AppDelegate.swift. The Expo template ` +
        "changed; update plugins/withIosCallKit.js.",
    );
  }
  return contents.replace(find, replace);
}

const withVoipBackgroundMode = (config) =>
  withInfoPlist(config, (config) => {
    const modes = Array.isArray(config.modResults.UIBackgroundModes)
      ? config.modResults.UIBackgroundModes
      : [];
    if (!modes.includes("voip")) modes.push("voip");
    config.modResults.UIBackgroundModes = modes;
    return config;
  });

const withHelperFiles = (config) =>
  withDangerousMod(config, [
    "ios",
    async (config) => {
      const projectName = IOSConfig.XcodeUtils.getProjectName(config.modRequest.projectRoot);
      const dir = path.join(config.modRequest.platformProjectRoot, projectName);
      fs.writeFileSync(path.join(dir, `${HELPER}.h`), HEADER);
      fs.writeFileSync(path.join(dir, `${HELPER}.m`), SOURCE);

      const bridgingHeader = path.join(dir, `${projectName}-Bridging-Header.h`);
      const line = `#import "${HELPER}.h"`;
      const current = fs.existsSync(bridgingHeader) ? fs.readFileSync(bridgingHeader, "utf8") : "";
      if (!current.includes(line)) {
        fs.writeFileSync(bridgingHeader, `${current.trimEnd()}\n${line}\n`);
      }
      return config;
    },
  ]);

const withHelperInProject = (config) =>
  withXcodeProject(config, (config) => {
    const project = config.modResults;
    const projectName = IOSConfig.XcodeUtils.getProjectName(config.modRequest.projectRoot);
    const source = `${projectName}/${HELPER}.m`;
    if (!project.hasFile(source)) {
      IOSConfig.XcodeUtils.addBuildSourceFileToGroup({
        filepath: source,
        groupName: projectName,
        project,
      });
    }
    const target = IOSConfig.XcodeUtils.getApplicationNativeTarget({ project, projectName });
    for (const framework of ["CallKit.framework", "PushKit.framework"]) {
      if (!project.hasFile(framework)) project.addFramework(framework, { target: target.uuid });
    }
    return config;
  });

const withPushKitDelegate = (config) =>
  withAppDelegate(config, (config) => {
    if (config.modResults.language !== "swift") {
      throw new Error("[withIosCallKit] Expected a Swift AppDelegate.");
    }
    let contents = config.modResults.contents;
    contents = replaceOnce(contents, "import React\n", "import React\nimport PushKit\n", "imports");
    contents = replaceOnce(
      contents,
      "class AppDelegate: ExpoAppDelegate {",
      "class AppDelegate: ExpoAppDelegate, PKPushRegistryDelegate {",
      "the AppDelegate class",
    );
    contents = replaceOnce(
      contents,
      "    return super.application(application, didFinishLaunchingWithOptions: launchOptions)",
      `    ${HELPER}.setup()\n\n    return super.application(application, didFinishLaunchingWithOptions: launchOptions)`,
      "didFinishLaunching's return",
    );
    contents = replaceOnce(
      contents,
      "  // Linking API\n",
      `${DELEGATE_METHODS}  // Linking API\n`,
      "the Linking API marker",
    );
    config.modResults.contents = contents;
    return config;
  });

module.exports = function withIosCallKit(config) {
  config = withVoipBackgroundMode(config);
  config = withHelperFiles(config);
  config = withHelperInProject(config);
  config = withPushKitDelegate(config);
  return config;
};
