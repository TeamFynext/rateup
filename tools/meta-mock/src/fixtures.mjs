import { readFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));

/**
 * A Graph version segment, however it is written.
 *
 * `v25.0` is what arrives at runtime; `{{Version}}` and `{{api_version}}` are
 * what Meta's two Postman collections use — they disagree with each other. Both
 * the request path stripper and the fixture generator need this, and when they
 * had a regex each the generator's understood the template forms and the
 * server's did not.
 */
export const VERSION_SEGMENT = /^(\{\{\s*[\w-]*version[\w-]*\s*\}\}|v\d+\.\d+)$/i;

/** Drop a leading version segment from a request path: `/v25.0/x` → `/x`. */
export function stripVersion(pathname) {
  const [, first, ...rest] = pathname.split("/");
  return VERSION_SEGMENT.test(first ?? "") ? `/${rest.join("/")}` : pathname;
}

/**
 * Meta's own request/response catalogue.
 *
 * Generated by `scripts/sync-from-postman.mjs` from the published "WhatsApp
 * Cloud API" collection, so the bodies served here are Meta's saved examples
 * rather than a guess at what Graph returns. Regenerate with `npm run sync`.
 */
export const fixtures = JSON.parse(
  readFileSync(path.join(HERE, "..", "graph-fixtures.json"), "utf8"),
);

/**
 * `?fields=preview.invalidate(false)` → `fields=preview`.
 *
 * Only `fields` distinguishes two Graph endpoints that share a path, and only
 * its leading token — the rest is arguments to that field.
 */
export function fieldSelector(query) {
  const fields = query.fields;
  if (!fields) return "";
  const first = String(fields).split(/[.,(]/)[0].trim();
  return first ? `fields=${first}` : "";
}

/**
 * Which API a request belongs to, read off the body.
 *
 * WhatsApp and Instagram share endpoints — `POST /{id}/messages` exists in both
 * and answers with completely different bodies, WhatsApp with a `messages[]`
 * envelope and Instagram with `{ recipient_id, message_id }`. The path cannot
 * separate them, but the request can: a Cloud API send always declares
 * `messaging_product`, and an Instagram send is a `recipient` plus a `message`.
 *
 * Returns null when there is nothing to go on, which leaves the caller's
 * default (WhatsApp) in charge.
 */
export function apiOf(body) {
  if (!body || typeof body !== "object") return null;
  if (body.messaging_product) return "whatsapp";
  if (body.recipient && body.message) return "instagram";
  return null;
}

/**
 * Find the fixture for a request.
 *
 * Patterns match segment by segment, with `:id` matching any single segment.
 * Where several match, the one with more literal segments wins —
 * `/:id/message_qrdls/:id` must not lose to `/:id/:id` — and a route carrying a
 * `fields=` selector beats the bare path when the request carries that field.
 *
 * `options.body` and `options.defaultApi` break the tie between the two APIs on
 * the four endpoints they share.
 */
export function matchFixture(method, pathname, query, options = {}) {
  const routes = options.routes ?? fixtures.routes;
  const preferred = apiOf(options.body) ?? options.defaultApi ?? "whatsapp";
  const wanted = pathname.split("/").filter(Boolean);
  const selector = fieldSelector(query);

  let best = null;
  let bestScore = -1;

  for (const route of routes) {
    if (route.method !== method) continue;

    const segments = route.path.split("/").filter(Boolean);
    if (segments.length !== wanted.length) continue;

    let literals = 0;
    let ok = true;
    for (let index = 0; index < segments.length; index++) {
      const segment = segments[index];
      if (segment === ":id") continue;
      if (segment !== wanted[index]) {
        ok = false;
        break;
      }
      literals++;
    }
    if (!ok) continue;

    if (route.select) {
      if (route.select !== selector) continue;
      literals += 10;
    }

    // The API tag is a weaker signal than path shape — a more specific path
    // from the other API should still win — so it only breaks ties.
    const score = literals * 2 + (route.api === preferred ? 1 : 0);

    if (score > bestScore) {
      bestScore = score;
      best = route;
    }
  }

  return best;
}

/**
 * Anything with neither a handler nor a fixture.
 *
 * Graph answers a write with `{ success: true }` and a collection read with
 * `{ data: [] }`, so mirroring that keeps an unmapped call from cascading into a
 * crash on a screen the caller was not even looking at. Every one is still
 * recorded and marked `matched: false`, so what was missed stays visible.
 */
export function fallbackResponse(method, mintId) {
  if (method === "GET") return { data: [], paging: { cursors: { before: "", after: "" } } };
  if (method === "DELETE") return { success: true };
  return { success: true, id: mintId() };
}
