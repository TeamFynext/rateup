import { createGraphRoutes } from "../src/graph-routes.mjs";

/**
 * Render the route table as Markdown.
 *
 * Reading `src/server.mjs` tells you nothing about what the mock answers: the
 * stateful handlers are regexes in one file, the generated routes are a 100 KB
 * JSON blob, and everything else falls through to a generic response. So the
 * question "what does this actually serve?" had no answer short of running it.
 *
 * ROUTES.md is that answer, regenerated on every sync and committed — so it
 * diffs when Meta changes something, and it is browsable without cloning.
 */

/**
 * The stateful handlers, as readable paths.
 *
 * Listing the handlers themselves rather than the fixture routes they shadow.
 * Shadowing reads badly: the bare-id handler matches `/{id}` whatever the query
 * string, so a shadow-based table marks all thirteen `GET /:id?fields=…`
 * fixtures as stateful when only flows and templates actually are.
 */
function statefulHandlers() {
  const rules = createGraphRoutes({
    state: { flows: new Map(), templates: new Map() },
    mintId: () => "1",
    publicUrl: () => "http://localhost",
  });

  return rules.map((rule) => ({
    method: rule.method,
    path: readablePattern(rule.match),
    conditional: !!rule.when,
  }));
}

/** `/^\/(?<wabaId>\d+)\/flows$/` → `/{wabaId}/flows`. */
function readablePattern(regex) {
  return regex.source
    .replace(/^\^/, "")
    .replace(/\$$/, "")
    .replaceAll("\\/", "/")
    .replace(/\(\?<(\w+)>[^)]*\)/g, "{$1}")
    .replaceAll("\\.", ".");
}

const escape = (text) => String(text).replaceAll("|", "\\|");

export function renderRoutesDoc({ collections, routes, webhooks, dropped }) {
  const lines = [];

  lines.push("# Routes");
  lines.push("");
  lines.push(
    "GENERATED by `scripts/sync-from-postman.mjs` — do not edit by hand. Run `npm run sync`.",
  );
  lines.push("");
  lines.push(
    "Every request is answered. These are the ones answered with **Meta's own example " +
      "response**, taken from its published Postman collections; anything not listed here still " +
      "gets a generic Graph-shaped reply (`{ data: [] }` for reads, `{ success: true }` for " +
      "writes) and is recorded with `matched: false`.",
  );
  lines.push("");

  lines.push("| Collection | Routes | Webhooks | Documented without an example |");
  lines.push("| --- | --- | --- | --- |");
  for (const collection of collections) {
    lines.push(
      `| [${escape(collection.name)}](${collection.page}) | ${collection.routes} | ` +
        `${collection.webhooks} | ${collection.dropped ?? 0} |`,
    );
  }
  lines.push("");

  const handlers = statefulHandlers();
  lines.push(`## Stateful (${handlers.length})`);
  lines.push("");
  lines.push(
    "These run **ahead of** the fixtures, because a canned example cannot model " +
      "created-then-listed-then-published-then-deleted. Everything here is WhatsApp: nothing " +
      "Instagram is stateful yet, so an ice-breakers write followed by a read returns the " +
      "collection's example rather than what was just written. Source: `src/graph-routes.mjs`.",
  );
  lines.push("");
  lines.push(
    "`conditional` means the handler only claims objects this mock created — an id it does " +
      "not know falls through to the fixture.",
  );
  lines.push("");
  lines.push("| Method | Path | Applies |");
  lines.push("| --- | --- | --- |");
  for (const handler of handlers) {
    lines.push(
      `| ${handler.method} | \`${escape(handler.path)}\` | ` +
        `${handler.conditional ? "conditional" : "always"} |`,
    );
  }
  lines.push("");

  for (const collection of collections) {
    const mine = routes.filter((route) => route.api === collection.api);
    if (mine.length === 0) continue;

    lines.push(`## ${collection.name}`);
    lines.push("");
    lines.push(`${mine.length} routes. Source: [the collection](${collection.page}).`);
    lines.push("");
    lines.push("| Method | Path | Request | Folder |");
    lines.push("| --- | --- | --- | --- |");

    for (const route of mine) {
      const path = `\`${escape(route.path)}${route.select ? `?${escape(route.select)}` : ""}\``;
      const variants = route.variants?.length ? ` *(+${route.variants.length} variants)*` : "";
      lines.push(
        `| ${route.method} | ${path} | ${escape(route.name)}${variants} | ${escape(route.folder)} |`,
      );
    }
    lines.push("");

    const hooks = webhooks.filter((hook) => hook.api === collection.api);
    if (hooks.length > 0) {
      lines.push(`### ${collection.name} webhooks`);
      lines.push("");
      lines.push(
        "Replay with `mock.replayWebhook({ name, from, wabaId })`. Pass the name exactly as " +
          "written here.",
      );
      lines.push("");
      for (const hook of hooks) lines.push(`- \`${escape(hook.qualifiedName ?? hook.name)}\``);
      lines.push("");
    }
  }

  const missing = dropped ?? [];
  if (missing.length > 0) {
    lines.push("## Documented, but with no example response");
    lines.push("");
    lines.push(
      `${missing.length} requests appear in Meta's collections without a saved response, so ` +
        "there is no body to serve and they fall through to the generic reply. Not a gap in " +
        "this mock — a gap in the source. If one of these starts mattering, give it a stateful " +
        "handler in `src/graph-routes.mjs`.",
    );
    lines.push("");
    lines.push("| API | Method | Path | Request |");
    lines.push("| --- | --- | --- | --- |");
    for (const entry of missing) {
      lines.push(
        `| ${entry.api} | ${entry.method} | \`${escape(entry.path)}\` | ${escape(entry.name)} |`,
      );
    }
    lines.push("");
  }

  return `${lines.join("\n")}\n`;
}
